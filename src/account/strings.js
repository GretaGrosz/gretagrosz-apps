export function useAccountText() {
  const { lang } = useLang()
  return (key, vars = {}) => {
    const text = TEXT[lang]?.[key] ?? TEXT.de[key] ?? key
    return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? `{${name}}`)
  }
}

// "Gesichert vor 3 Min." aus einem Zeitpunkt
export function syncedText(t, at, now = Date.now()) {
  if (!at) return t('syncedNow')
  const min = Math.floor((now - at) / 60_000)
  if (min < 1) return t('syncedNow')
  if (min < 60) return t('syncedMin', { n: min })
  const h = Math.floor(min / 60)
  if (h < 24) return t('syncedHours', { n: h })
  return t('syncedDays', { n: Math.floor(h / 24) })
}
