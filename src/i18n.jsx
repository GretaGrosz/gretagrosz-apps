const LangContext = createContext({ lang: 'de', setLang: () => {}, t: (k) => k, langKnown: true })

export function LanguageProvider({ children }) {
  const [{ lang, known }, setState] = useState(initialLang)

  useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])

  const value = useMemo(() => {
    const setLang = (code) => {
      // Übergang: die alte Sprache bleibt sichtbar, bis die Inhalte der neuen geladen sind
      startTransition(() => setState({ lang: code, known: true }))
      try {
        localStorage.setItem(OWN_KEY, code)
        if (code === 'de' || code === 'en') localStorage.setItem(SITE_KEY, code)
      } catch {
        /* ignorieren */
      }
    }
    const t = (key, vars = {}) => {
      const text = UI[lang]?.[key] ?? UI.de[key] ?? key
      return text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`))
    }
    return { lang, setLang, t, langKnown: known }
  }, [lang, known])

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>
}

export function useLang() {
  return useContext(LangContext)
}
