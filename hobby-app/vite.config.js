import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'
import { createHash } from 'node:crypto'

// Writes sw.js into the build: it precaches the app (index.html + hashed assets + icons) under a version
// derived from their contents, so Blank opens offline and a new deploy replaces the old cache in one step.
// Idea photos are cached the first time you see them. API calls (/blank/api/*) are never cached.
function serviceWorker() {
  let base = '/'
  return {
    name: 'blank-service-worker',
    enforce: 'post',
    apply: 'build',
    configResolved(config) {
      base = config.base
    },
    generateBundle(_, bundle) {
      const files = Object.keys(bundle).filter((f) => !f.endsWith('.map'))
      const hash = createHash('sha256')
      for (const f of files.sort()) hash.update(f).update(bundle[f].code || bundle[f].source || '')
      const version = hash.digest('hex').slice(0, 12)
      const precache = [
        base,
        ...['manifest.webmanifest', 'logo.png', 'icon-192.png', 'apple-touch-icon.png'].map((f) => base + f),
        ...files.filter((f) => f !== 'index.html').map((f) => base + f),
      ]
      const source = `// Blank's service worker (generated by vite.config.js, do not edit)
const VERSION = ${JSON.stringify(version)}
const BASE = ${JSON.stringify(base)}
const PRECACHE = ${JSON.stringify(precache)}
const APP = 'blank-app-' + VERSION
const PHOTOS = 'blank-ideas-v1'

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(APP).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    for (const key of await caches.keys()) if (key.startsWith('blank-app-') && key !== APP) await caches.delete(key)
    await self.clients.claim()
  })())
})

const offline = () => new Response('', { status: 504, statusText: 'Offline' })

self.addEventListener('fetch', (e) => {
  const req = e.request
  if (req.method !== 'GET') return
  const url = new URL(req.url)
  if (url.origin !== location.origin || !url.pathname.startsWith(BASE)) return
  if (url.pathname.startsWith(BASE + 'api/')) return
  // The app itself: from the cache, instantly, with or without a connection
  if (req.mode === 'navigate') {
    e.respondWith(caches.match(BASE, { cacheName: APP }).then((hit) => hit || fetch(req)).catch(offline))
    return
  }
  if (url.pathname.startsWith(BASE + 'ideas/')) {
    e.respondWith(caches.open(PHOTOS).then(async (c) => {
      const hit = await c.match(req)
      if (hit) return hit
      const res = await fetch(req)
      if (res.ok) c.put(req, res.clone())
      return res
    }).catch(offline))
    return
  }
  e.respondWith(caches.match(req, { cacheName: APP }).then((hit) => hit || fetch(req)).catch(offline))
})

// Buddy notifications
self.addEventListener('push', (e) => {
  let d = {}
  try { d = e.data.json() } catch {}
  e.waitUntil(self.registration.showNotification(d.title || 'Blank', {
    body: d.body || '',
    tag: d.tag,
    renotify: !!d.tag,
    icon: BASE + 'icon-192.png',
    data: { url: d.url || '' },
  }))
})

self.addEventListener('notificationclick', (e) => {
  e.notification.close()
  e.waitUntil((async () => {
    const open = await self.clients.matchAll({ type: 'window', includeUncontrolled: true })
    const app = open.find((c) => new URL(c.url).pathname.startsWith(BASE))
    const url = e.notification.data && e.notification.data.url
    const target = BASE + (url || '')
    if (app) {
      await app.focus()
      // The axolotl's reminder opens its project (url is '#/project/<id>')
      if (url) await app.navigate(target).catch(() => {})
      return
    }
    return self.clients.openWindow(target)
  })())
})
`
      this.emitFile({ type: 'asset', fileName: 'sw.js', source })
    },
  }
}

export default defineConfig({
  plugins: [react(), serviceWorker()],
  server: {
    // The buddy API runs in the worker: `npx wrangler dev --local --port 5249` from the repo root
    // The worker refuses POSTs from another origin, so the proxy sends the worker's own origin
    proxy: {
      '/blank/api': {
        target: 'http://localhost:5249',
        changeOrigin: true,
        configure: (proxy) => proxy.on('proxyReq', (req) => { if (req.getHeader('origin')) req.setHeader('origin', 'http://localhost:5249') }),
      },
    },
  },
})
