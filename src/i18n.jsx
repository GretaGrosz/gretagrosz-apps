// Sprachen der App. Inhalte (Lerninhalte, Quizfragen) sind auf Deutsch geschrieben und übersetzt;
// fehlt eine Übersetzung, wird Deutsch angezeigt.
export const LANGUAGES = [
  { code: 'de', label: 'Deutsch', short: 'DE' },
  { code: 'en', label: 'English', short: 'EN' },
  { code: 'hu', label: 'Magyar', short: 'HU' },
]

const OWN_KEY = 'bw-buddy-lang'
// Gemeinsamer Schlüssel aller Seiten auf gretagrosz.com ('de' | 'en') – wer die Seite auf Englisch
// gelesen hat, bekommt BW Buddy auf Englisch.
const SITE_KEY = 'lang'
const codes = LANGUAGES.map((l) => l.code)

function readKey(key) {
  try {
    return localStorage.getItem(key)
  } catch {
    return null
  }
}

// Erste Sprache: Ungarisch (kann die Website nicht ausdrücken) → Website-Sprache → eigene Wahl → Gerät → Deutsch.
// known: ob die Sprache feststeht (dann fragt die Einrichtung nicht danach).
export function initialLang() {
  const own = readKey(OWN_KEY)
  const site = readKey(SITE_KEY)
  if (own === 'hu') return { lang: 'hu', known: true }
  if (site === 'de' || site === 'en') return { lang: site, known: true }
  if (codes.includes(own)) return { lang: own, known: true }
  const device = (navigator.languages || [navigator.language || '']).map((l) => String(l).slice(0, 2).toLowerCase()).find((l) => codes.includes(l))
  return device ? { lang: device, known: true } : { lang: 'de', known: false }
}

