export default function Icon({ name, size = 20, className = '', strokeWidth = 2, title }) {
  const parts = P[name] || P.square
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={strokeWidth} strokeLinecap="round" strokeLinejoin="round"
      className={`inline-block shrink-0 ${className}`} aria-hidden={title ? undefined : true} role={title ? 'img' : undefined}>
      {title && <title>{title}</title>}
      {parts.map((d, i) => {
        if (d.startsWith('circle:')) { const [cx, cy, r] = d.slice(7).split(',').map(Number); return <circle key={i} cx={cx} cy={cy} r={r} /> }
        if (d.startsWith('rect:')) { const [x, y, w, h, rx] = d.slice(5).split(',').map(Number); return <rect key={i} x={x} y={y} width={w} height={h} rx={rx} /> }
        if (d.startsWith('fill:')) return <path key={i} d={d.slice(5)} fill="currentColor" stroke="none" />
        return <path key={i} d={d} />
      })}
    </svg>
  )
}

